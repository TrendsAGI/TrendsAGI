import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const input = pathToFileURL(path.join(root, "openapi.json"));
const output = path.join(root, "packages/core/src/schema.d.ts");

const ast = await openapiTS(input);
const contents = astToString(ast);
await mkdir(path.dirname(output), { recursive: true });
await writeFile(
  output,
  `// Generated by scripts/generate-schema.mjs from openapi.json. Do not edit by hand.\n${contents}`,
);

console.log(`Wrote ${path.relative(root, output)} (${contents.length} bytes)`);
